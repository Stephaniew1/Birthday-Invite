@app.route("/chat", methods=["POST"])
def chat():
    """
    AJAX endpoint for front-end to send a user's message and receive the bot's reply.
    We'll store the user's state in the Flask session.
    """
    user_message = request.json.get("message", "").strip()

    # If user restarts or is new
    if "state" not in session or user_message.lower() == "secret":
        session["state"] = "waiting_for_secret"
        return jsonify({"reply": MESSAGES["intro"]})

    current_state = session["state"].lower()
    lower_msg = user_message.lower()

    # Handle "waiting_for_email" -> validate email
    if current_state == "waiting_for_email":
        if re.match(r"[^@]+@[^@]+\.[^@]+", lower_msg):
            # Valid email -> send ICS invite via Gmail
            send_gmail_invite(lower_msg)
            session.pop("state", None)
            reply = MESSAGES["email_confirm"].format(email=user_message)
            return jsonify({"reply": reply})
        else:
            return jsonify({"reply": MESSAGES["invalid_email"]})

    # waiting_for_secret
    if current_state == "waiting_for_secret":
        if lower_msg in ["1", "yes"]:
            session["state"] = "waiting_for_booking"
            return jsonify({"reply": MESSAGES["waiting_for_booking"]})
        elif lower_msg in ["2", "no"]:
            return jsonify({"reply": MESSAGES["asking_friends"]})

    # waiting_for_booking
    if current_state == "waiting_for_booking":
        if lower_msg in ["2", "no"]:
            session["state"] = "waiting_for_email"
            return jsonify({"reply": MESSAGES["email_prompt"]})
        elif lower_msg in ["1", "yes"]:
            return jsonify({"reply": MESSAGES["no_worries"]})

    # Fallback
    return jsonify({"reply": MESSAGES["didnt_understand"]})



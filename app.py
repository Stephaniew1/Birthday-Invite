def restore_files_from_env():
    # Decode credentials.json
    creds_b64 = os.environ.get("CREDENTIALS_JSON_B64")
    token_b64 = os.environ.get("TOKEN_JSON_B64")
    if creds_b64:
        with open("credentials.json", "wb") as f:
            f.write(base64.urlsafe_b64decode(creds_b64))
    if token_b64:
        with open("token.json", "wb") as f:
            f.write(base64.urlsafe_b64decode(token_b64))

restore_files_from_env()



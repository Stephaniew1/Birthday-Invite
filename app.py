# ------------------ GMAIL SENDING SETUP -------------------
def get_gmail_credentials():
    """
    Load & refresh (if needed) the Gmail API credentials from token.json.
    token.json must be generated by running get_gmail_token.py once.
    """
    creds = Credentials.from_authorized_user_file("token.json", SCOPES)
    if creds.expired and creds.refresh_token:
        creds.refresh(google.auth.transport.requests.Request())
    return creds


def send_gmail_invite(to_email):
    """
    Send an email with a .ics calendar invite attached via Gmail API.
    """
    ics_str = create_ics_file(to_email)

    # 1) multipart message
    message = MIMEMultipart()
    message["to"] = to_email
    message["subject"] = f"🎉 You're Invited to {EVENT_NAME}"

    # 2) Plain text body
    body_text = (
        f"Hey! You are invited to Dr. Wanjiru's Surprise birthday Party!\n\n"
        f"📅 Date: {EVENT_DATE}\n"
        f"📍 Location: {EVENT_LOCATION}\n\n"
        "See attached calendar invite! Click to add to calendar. "
    )
    part_text = MIMEText(body_text, "plain", _charset="utf-8")
    message.attach(part_text)

    # 3) .ics attachment as base64
    part_ics = MIMEBase("text", "calendar", charset="utf-8")
    part_ics.set_payload(ics_str.encode("utf-8"))  # convert to bytes
    encoders.encode_base64(part_ics)  # base64-encode
    part_ics.add_header("Content-Transfer-Encoding", "base64")
    part_ics.add_header(
        "Content-Disposition", "attachment", filename="event-invite.ics"
    )
    part_ics.add_header("Content-Class", "urn:content-classes:calendarmessage")

    message.attach(part_ics)

    # 4) Convert entire message to base64 for Gmail
    raw_message = base64.urlsafe_b64encode(message.as_bytes()).decode("utf-8")
    body = {"raw": raw_message}

    # 5) Send via Gmail
    creds = get_gmail_credentials()
    service = build("gmail", "v1", credentials=creds)
    try:
        result = service.users().messages().send(userId="me", body=body).execute()
        print("Email sent! Message ID:", result["id"])
        return True
    except Exception as e:
        print("Error sending via Gmail API:", e)
        return False



def create_ics_file(email):
    """
    Generate a .ics file content with event details.
    """
    start_time = datetime.datetime.strptime(EVENT_DATE, "%Y-%m-%d %H:%M:%S")
    end_time = start_time + datetime.timedelta(hours=EVENT_DURATION)

